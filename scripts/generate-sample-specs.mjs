/**
 * Generates Tesserae.Flint.Sample/src/SampleSpecs.g.cs from the flint-json
 * files in Tesserae.Flint.Sample/specs/. The JSON files are the single source
 * of truth — the spec tests glob the same directory, and adding a sample to
 * the gallery is just a file drop.
 *
 * Run from the Tesserae.Flint.Sample directory (the csproj does this before
 * every build): node ../scripts/generate-sample-specs.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, basename } from 'node:path';

const specsDir = join(process.cwd(), 'specs');
const outFile  = join(process.cwd(), 'src', 'SampleSpecs.g.cs');

const files = (await readdir(specsDir))
  .filter(f => f.endsWith('.json'))
  .sort();

if (files.length === 0) {
  console.error(`generate-sample-specs: no *.json files found in ${specsDir}`);
  process.exit(1);
}

/** "01-bar.json" → "01 Bar", "03-scatter-color.json" → "03 Scatter Color" */
function displayName(file) {
  return basename(file, '.json')
    .split('-')
    .map(part => /^\d+$/.test(part) ? part : part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

/** Escapes text for a C# verbatim string literal (@"..."). */
function verbatim(text) {
  return '@"' + text.replace(/"/g, '""') + '"';
}

const samples = [];
for (const file of files) {
  // Normalize CRLF so autocrlf checkouts regenerate byte-identical output.
  const raw = (await readFile(join(specsDir, file), 'utf8')).replace(/\r\n/g, '\n');
  JSON.parse(raw); // validate — fail the build on malformed spec files
  samples.push({ name: displayName(file), json: raw.trimEnd() });
}

const entries = samples.map(s => `            new Sample(
                ${verbatim(s.name)},
${verbatim(s.json).split('\n').map((l, i) => (i === 0 ? '                ' + l : l)).join('\n')})`).join(',\n');

const code = `// <auto-generated>
//   GENERATED by scripts/generate-sample-specs.mjs — DO NOT EDIT.
//   Edit the flint-json files in Tesserae.Flint.Sample/specs/ instead;
//   this file is regenerated on every build.
// </auto-generated>

namespace Tesserae.Flint.Sample
{
    /// <summary>
    /// Flint-json sample specs rendered by the gallery, generated from
    /// <c>specs/*.json</c>. Those JSON files are the single source of truth:
    /// the spec tests glob <c>Tesserae.Flint.Sample/specs/*.json</c> directly,
    /// so a new sample only needs a new file there.
    /// </summary>
    public static class SampleSpecs
    {
        public class Sample
        {
            public Sample(string name, string json) { Name = name; Json = json; }

            public string Name { get; }
            public string Json { get; }
        }

        public static readonly Sample[] All = new[]
        {
${entries}
        };
    }
}
`;

await writeFile(outFile, code);
console.log(`generate-sample-specs: wrote ${outFile} (${samples.length} samples: ${samples.map(s => s.name).join(', ')})`);
